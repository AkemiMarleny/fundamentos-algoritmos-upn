#Algoritmo: Sommare due numeri
# 1. Definire le variabili per i numeri (num1, num2)
# 2. Richiedere all'utente di inserire il primero numero
# 3. Richiedere all'utente di inserire il secondo numero
# 4. Calcolare la somma: risultato = num1 + num2
# 5. Mostrare il risultato all'utente

#Implementazione in Python:

num1 = float(input("Inserisce il primo numero: "))
